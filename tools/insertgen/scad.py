"""Layout -> BIT .scad source (one file, every tray; pick one with -D which="<tray id>")."""
import os
from pathlib import Path

from .model import Game, Rules
from .solver import Layout

BIT_LIB = Path(__file__).resolve().parents[2] / "vendor" / "bit" / "boardgame_insert_toolkit_lib.4.12.0.scad"


def _n(v: float) -> str:
    return f"{v:.2f}".rstrip("0").rstrip(".")


def _vec(*vs: float) -> str:
    return "[" + ", ".join(_n(v) for v in vs) + "]"


def _features(p, rules: Rules) -> list[str]:
    X, Y, Z = p.size
    wells = p.tray.wells
    row = sum(w.x for w in wells) + rules.divider * (len(wells) - 1)
    x = (X - row) / 2
    out = []
    for w in wells:
        # BIT measures POSITION_XY from the interior corner, i.e. offset by G_WALL_THICKNESS (= floor here).
        lines = [f"[ FTR_COMPARTMENT_SIZE_XYZ, {_vec(w.x, w.y, Z - rules.floor)} ]",
                 f"[ POSITION_XY, {_vec(x - rules.floor, (Y - w.y) / 2 - rules.floor)} ]"]
        if w.kind == "cards":
            lines.append("[ FTR_CUTOUT_SIDES_4B, [t, t, f, f] ]")
        elif w.kind == "tokens":
            lines.append("[ FTR_SHAPE, FILLET ]")
        out.append(f"        [ BOX_FEATURE,  // {w.label}{' (upright)' if w.upright else ''}\n"
                   + "".join(f"            {line},\n" for line in lines) + "        ],")
        x += w.x + rules.divider
    return out


def render_scad(game: Game, rules: Rules, layout: Layout, scad_path: Path) -> str:
    lib = os.path.relpath(BIT_LIB, scad_path.parent)
    boxes = []
    for p in layout.placements:
        boxes.append(
            f"    [ OBJECT_BOX,\n"
            f"        [ NAME, \"{p.tray.id}\" ],\n"
            f"        [ BOX_SIZE_XYZ, {_vec(*p.size)} ],  // exterior\n"
            f"        [ BOX_NO_LID_B, t ],\n"
            + "\n".join(_features(p, rules)) + "\n    ],")
    return (
        f"// GENERATED by insertgen from game.yaml ({game.name}). Do not edit; edit game.yaml and rebuild.\n"
        f"include <{lib}>;\n\n"
        f"which = \"\";  // tray NAME to export, empty = all\n\n"
        f"data = [\n"
        f"    [ G_PRINT_BOXES, which ],\n"
        # BIT's wall global is only used for its floor check and the feature offset; real walls come from sizes.
        f"    [ G_WALL_THICKNESS, {_n(rules.floor)} ],\n"
        + "\n".join(boxes) + "\n];\n\nMake(data);\n")


def render_assembly(game: Game, layout: Layout, stl_dir: Path, path: Path) -> str:
    """Trays (as rendered STLs) at their solved positions, inside a ghost of the box."""
    X, Y, Z = game.box.inner_xyz
    rel = os.path.relpath(stl_dir, path.parent)
    parts = []
    for p in layout.placements:
        x, y = p.x + layout.offset, p.y + layout.offset
        # A rotated tray's local X runs along box Y; rotate 90 deg and shift back into place.
        move = (f"translate({_vec(x + p.w, y, p.z)}) rotate([0, 0, 90])" if p.rotated
                else f"translate({_vec(x, y, p.z)})")
        parts.append(f"{move} color(\"SteelBlue\") import(\"{rel}/{p.tray.id}.stl\");")
    z = layout.usable_h + 0.1      # tiny gap avoids z-fighting with tray tops in the preview
    for t in game.on_top:
        tx, ty, tz = t.xyz
        parts.append(f"translate({_vec((X - tx) / 2, (Y - ty) / 2, z)}) color(\"Wheat\", 0.35) cube({_vec(tx, ty, tz)});")
        z += tz
    return ("// GENERATED by insertgen: trays in the box (box walls are a 2 mm ghost around the measured interior).\n"
            + "\n".join(parts) + "\n"
            + f"%difference() {{ translate([-2, -2, -2]) cube({_vec(X + 4, Y + 4, Z + 2)}); cube({_vec(X, Y, Z + 1)}); }}\n")
